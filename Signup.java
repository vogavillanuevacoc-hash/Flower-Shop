    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed

         String name = txtName.getText().trim();
         String Lastname = txtLastname.getText().trim();
    String email = txtEmail.getText().trim();
    String mobile = txtMobileNumber.getText().trim();
    String address = txtAddress.getText().trim();
    String password = new String(txtPassword.getPassword());
    String securityQuestion = txtSecurityQuestion.getText().trim();
    String answer = txtAnswer.getText().trim();

    String sql = "INSERT INTO users "
            + "(`Firstname`, `Lastname`, `Email`, `Mobile Number`, `Address`, `Password`, "
            + "`Security Question`, `Answer`, `role`) "
            + "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)";

    try (PreparedStatement pst = conn.prepareStatement(sql)) {

        pst.setString(1, name);
        pst.setString(2, Lastname);
        pst.setString(3, email);
        pst.setString(4, mobile);
        pst.setString(5, address);
        pst.setString(6, password);
        pst.setString(7, securityQuestion);
        pst.setString(8, answer);
        pst.setString(9, "customer");  // THIS IS PARAMETER 8

        pst.executeUpdate();

        JOptionPane.showMessageDialog(
                this,
                "User registered successfully!"
        );

        clear();

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Insert Error:\n" + e.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE
        );

        e.printStackTrace();
    }

// TODO add your handling code here:
    }//GEN-LAST:event_btnSaveActionPerformed

