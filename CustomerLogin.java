    private void btnForgotPasswordActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnForgotPasswordActionPerformed
        // TODO add your handling code here:
        
         String email = JOptionPane.showInputDialog(
        this,
        "Enter your registered email:",
        "Forgot Password",
        JOptionPane.QUESTION_MESSAGE
    );

    if (email == null || email.trim().isEmpty()) {
        return;
    }

    email = email.trim();

    String sql =
        "SELECT `Security Question`, Answer FROM users WHERE Email = ?";

    try (PreparedStatement pst = conn.prepareStatement(sql)) {

        pst.setString(1, email);

        try (ResultSet rs = pst.executeQuery()) {

            if (rs.next()) {

                String question = rs.getString("Security Question");
                String correctAnswer = rs.getString("Answer");

                String answer = JOptionPane.showInputDialog(
                    this,
                    question,
                    "Security Question",
                    JOptionPane.QUESTION_MESSAGE
                );

                if (answer != null &&
                    answer.trim().equalsIgnoreCase(correctAnswer.trim())) {

                    String newPassword = JOptionPane.showInputDialog(
                        this,
                        "Enter your new password:",
                        "Reset Password",
                        JOptionPane.QUESTION_MESSAGE
                    );

                    if (newPassword != null &&
                        !newPassword.trim().isEmpty()) {

                        String updateSQL =
                            "UPDATE users SET Password = ? WHERE Email = ?";

                        try (PreparedStatement updatePst =
                                 conn.prepareStatement(updateSQL)) {

                            updatePst.setString(1, newPassword);
                            updatePst.setString(2, email);

                            updatePst.executeUpdate();

                            JOptionPane.showMessageDialog(
                                this,
                                "Password successfully changed!",
                                "Success",
                                JOptionPane.INFORMATION_MESSAGE
                            );
                        }
                    }

                } else {

                    JOptionPane.showMessageDialog(
                        this,
                        "Incorrect answer.",
                        "Reset Failed",
                        JOptionPane.ERROR_MESSAGE
                    );
                }

            } else {

                JOptionPane.showMessageDialog(
                    this,
                    "No account was found with that email.",
                    "Account Not Found",
                    JOptionPane.WARNING_MESSAGE
                );
            }
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
            this,
            "Database Error:\n" + e.getMessage(),
            "Error",
            JOptionPane.ERROR_MESSAGE
        );

        e.printStackTrace();
    }

    }//GEN-LAST:event_btnForgotPasswordActionPerformed

