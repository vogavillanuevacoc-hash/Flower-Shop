    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
 String inputEmail = txtEmail.getText().trim();
    String inputPass = new String(txtPassword.getPassword());

    // Check empty fields
    if (inputEmail.isEmpty() || inputPass.isEmpty()) {

        JOptionPane.showMessageDialog(
            this,
            "Please enter your email and password.",
            "Login Error",
            JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    // Check email format
    if (!inputEmail.matches(emailPattern)) {

        JOptionPane.showMessageDialog(
            this,
            "Please enter a valid email address.",
            "Invalid Email",
            JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    String sql =
        "SELECT * FROM users WHERE Email = ? AND Password = ?";

    try (PreparedStatement pst = conn.prepareStatement(sql)) {

        pst.setString(1, inputEmail);
        pst.setString(2, inputPass);

        try (ResultSet rs = pst.executeQuery()) {

            if (rs.next()) {

                String name = rs.getString("Firstname");
                String role = rs.getString("role");

                JOptionPane.showMessageDialog(
                    this,
                    "Login Successful!\nWelcome, " + name + "!"
                );

                this.dispose();

                if ("admin".equalsIgnoreCase(role)) {

                    FlowerInventory admin = new FlowerInventory();
                    admin.setVisible(true);

                } else {

                    int userId = rs.getInt("User_id");

HomePage home = new HomePage(userId);
home.setVisible(true);

this.dispose();
                }

            } else
            
            {

                JOptionPane.showMessageDialog(
                    this,
                    "Invalid email or password.",
                    "Login Failed",
                    JOptionPane.ERROR_MESSAGE
                );
            }
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
            this,
            "Database Error:\n" + e.getMessage(),
            "Error",
            JOptionPane.ERROR_MESSAGE
        );

        e.printStackTrace();
    }
    


    }//GEN-LAST:event_btnLoginActionPerformed

